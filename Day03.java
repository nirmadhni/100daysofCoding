public class Day03 {
    public static void main(String[] args) {

        // Penggunaan \n
        System.out.println("Escape Sequence \\n");
        System.out.println("\\n digunakan untuk membuat baris baru.\nContohnya seperti ini.");

        // Penggunaan \t
        System.out.println("\nEscape Sequence \\t");
        System.out.println("\\t digunakan untuk memberikan jarak atau tab.\nContoh\t: Seperti ini.");

        // Penggunaan \"
        System.out.println("\nEscape Sequence \\\"");
        System.out.println("\\\" digunakan untuk menampilkan tanda petik.");
        System.out.println("Contoh: \"halo, saya sedang belajar Java\"");

        // Penggunaan \\
        System.out.println("\nEscape Sequence \\\\");
        System.out.println("\\\\ digunakan untuk menampilkan tanda backslash.");
        System.out.println("Contoh: C:\\Users\\nirmadhni");
    }
}
