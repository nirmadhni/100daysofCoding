public class Day08 {
    public static void main(String[] args) {

        // Deklarasi: membuat variabel dan menentukan tipe datanya
        String nama;
        int umur;

        // Inisialisasi: memberikan nilai awal ke variabel
        nama = "Nirma";
        umur = 18;

        System.out.println("Nama: " + nama);
        System.out.println("Umur: " + umur);

        // Update: mengubah nilai variabel yang sebelumnya sudah ada
        umur = 19;

        System.out.println("Umur setelah di-update: " + umur);
    }
}
