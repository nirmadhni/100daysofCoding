public class Day15 {
    public static void main(String[] args) {

        // Operator Perkalian (*)
        int angka1 = 10;
        int angka2 = 5;
        int hasilKali = angka1 * angka2;

        System.out.println("Hasil Perkalian: " + hasilKali);

        // Operator Pembagian (/)
        int angka3 = 20;
        int angka4 = 4;
        int hasilBagi = angka3 / angka4;

        System.out.println("Hasil Pembagian: " + hasilBagi);
    }
}
