public class Day09 {
    public static void main(String[] args) {

        // final digunakan untuk membuat nilai tetap
        final double PHI = 3.14;

        // nilai PHI tidak bisa diubah lagi
        System.out.println("Nilai PHI: " + PHI);

        // contoh konstanta lainnya
        final int TAHUN_LAHIR = 2008;

        // nilai tahun lahir juga tidak bisa diubah
        System.out.println("Tahun lahir: " + TAHUN_LAHIR);
    }
}
