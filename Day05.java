public class Day05 {
    public static void main(String[] args) {

        // double digunakan untuk menyimpan angka pecahan dengan ketelitian tinggi
        double tinggi = 156.5;
        double berat = 50.5;

        // float digunakan untuk menyimpan angka pecahan dan harus menggunakan huruf f
        float nilai = 89.5f;

        System.out.println("Tinggi badan: " + tinggi);
        System.out.println("Berat badan: " + berat);
        System.out.println("Nilai: " + nilai);
    }
}
